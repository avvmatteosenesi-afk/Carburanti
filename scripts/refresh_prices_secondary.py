#!/usr/bin/env python3
"""Refresh prices from a public MIMIT mirror when the primary dataset is stale.
Keeps the station registry generated by update_data.py and replaces only price rows.
"""
import csv, io, json, re, urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'data'
MIRRORS=[
 'https://raw.githubusercontent.com/cascafico/FuelPrices/main/prezzo_alle_8.csv',
]
FUELS={'benzina':'benzina','gasolio':'gasolio','gpl':'gpl','metano':'metano'}

def fetch(url):
 req=urllib.request.Request(url,headers={'User-Agent':'Carburanti-PWA/1.1','Accept':'text/csv,*/*'})
 with urllib.request.urlopen(req,timeout=45) as r:return r.read().decode('utf-8-sig','replace')

def extraction_date(text):
 for line in text.splitlines()[:5]:
  m=re.search(r'(20\d{2})[-/]?(\d{2})[-/]?(\d{2})',line)
  if m:
   try:return datetime(int(m[1]),int(m[2]),int(m[3]),tzinfo=timezone.utc)
   except ValueError:pass
 return None

def rows(text):
 lines=[x for x in text.splitlines() if x.strip()]
 idx=next((i for i,x in enumerate(lines[:10]) if 'idimpianto' in x.lower().replace(' ','')),None)
 if idx is None: raise RuntimeError('header prezzi non trovato')
 delim='|' if '|' in lines[idx] else ';'
 return csv.DictReader(io.StringIO('\n'.join(lines[idx:])),delimiter=delim)

def parse_dt(v):
 for f in ('%d/%m/%Y %H:%M:%S','%d/%m/%Y','%Y%m%d','%Y-%m-%d'):
  try:return datetime.strptime((v or '').strip(),f).replace(tzinfo=timezone.utc)
  except ValueError:pass
 return None

def main():
 p=DATA/'stations-it.json'; payload=json.loads(p.read_text(encoding='utf-8'))
 snap=payload.get('metadata',{}).get('source_snapshot_date')
 current=datetime.fromisoformat(snap).replace(tzinfo=timezone.utc) if snap else datetime.fromisoformat(payload['metadata']['generated_at'].replace('Z','+00:00'))
 text=url=None; ext=None
 for u in MIRRORS:
  try:
   t=fetch(u); d=extraction_date(t)
   if d and d.date()>current.date(): text,url,ext=t,u,d; break
  except Exception as e: print(f'Mirror non disponibile {u}: {e}')
 if not text:
  print('Nessun mirror con estrazione più recente: mantengo dataset corrente.'); return
 byid={str(s['id']):s for s in payload['stations']}
 selected={}
 for r in rows(text):
  low={str(k).strip().lower():str(v or '').strip() for k,v in r.items() if k}
  sid=low.get('idimpianto',''); desc=low.get('desccarburante','').lower().strip()
  fuel=FUELS.get(desc)
  if sid not in byid or not fuel: continue
  try: price=float(low.get('prezzo','').replace(',','.'))
  except ValueError: continue
  if not (0<price<10): continue
  selfv=low.get('isself','') in ('1','true','True')
  dt=parse_dt(low.get('dtcomu',''))
  key=(sid,fuel); cand=(selfv,dt or datetime.min.replace(tzinfo=timezone.utc),price)
  old=selected.get(key)
  if old is None or (cand[0] and not old[0]) or (cand[0]==old[0] and cand[1]>=old[1]): selected[key]=cand
 for (sid,fuel),(selfv,dt,price) in selected.items():
  byid[sid].setdefault('prices',{})[fuel]={'price':round(price,3),'self':selfv,'updated':dt.isoformat() if dt.year>1 else None}
 payload['metadata'].update({'source_mode':'mimit-secondary-mirror','source_prices':url,'source_snapshot_date':ext.date().isoformat(),'generated_at':datetime.now(timezone.utc).isoformat()})
 p.write_text(json.dumps(payload,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
 # Apply the same refreshed prices to Tuscany while preserving its geographic validation.
 tp=DATA/'stations.json'; tus=json.loads(tp.read_text(encoding='utf-8'))
 for s in tus['stations']:
  src=byid.get(str(s['id']))
  if src:s['prices']=src.get('prices',{})
 tus['metadata'].update({'source_mode':'mimit-secondary-mirror','source_prices':url,'source_snapshot_date':ext.date().isoformat(),'generated_at':payload['metadata']['generated_at']})
 tp.write_text(json.dumps(tus,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
 print(f'Prezzi aggiornati dal mirror MIMIT: estrazione {ext.date()}, {len(selected)} combinazioni impianto/carburante.')
if __name__=='__main__': main()
